import mongoose from "mongoose";

const helpRequestSchema = new mongoose.Schema(
  {
    title: {
      type: String,
      required: true,
    },

    description: {
      type: String,
      required: true,
    },

    location: {
      type: String,
      required: true,
    },

    status: {
      type: String,
      default: "Pending",
    },
  },
  {
    timestamps: true,
  }
);

const HelpRequest = mongoose.model(
  "HelpRequest",
  helpRequestSchema
);

export default HelpRequest;